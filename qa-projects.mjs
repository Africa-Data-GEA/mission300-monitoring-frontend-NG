import { chromium } from 'playwright'
const BASE='http://localhost:5179'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport:{width:1500,height:1100} })
const errs=[]
page.on('console', m=>{ if(m.type()==='error') errs.push(m.text()) })
page.on('pageerror', e=>errs.push('PAGEERROR: '+e.message))
await page.goto(`${BASE}/account/login`,{waitUntil:'networkidle'})
await page.locator('input[type="email"]').first().fill('admin@m300.local')
await page.locator('button[type="submit"]').first().click()
await page.waitForURL('**/account/password')
await page.locator('input[name="password"]').first().fill('ChangeMe123!')
await page.locator('button[type="submit"]').first().click()
await page.waitForURL('**/dashboard',{timeout:20000})
await page.waitForTimeout(9000)
const t = await page.locator('body').innerText()
const m = t.match(/Showing[^\n]*records/g)
console.log('count lines:', m)
const idx = t.indexOf('Priority project delivery status')
console.log('--- section text ---')
console.log(t.slice(idx, idx+700))
console.log('console errors:', errs.length?errs.slice(0,5):'none')
await browser.close()
