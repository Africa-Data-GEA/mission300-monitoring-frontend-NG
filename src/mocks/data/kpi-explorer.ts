export function getKpiProfile(id: string): KpiProfile | undefined {
  const bespoke = PROFILES[id]
  if (bespoke) return bespoke

  const row = CATALOGUE.find((entry) => entry.id === id)
  return row ? fallbackProfile(row) : undefined
}

/**
 * Publishes one value extracted from an approved or provisionally-accepted
 * data submission: appends a history point and updates the current value in
 * place, so the KPI Explorer reflects it on the next fetch. This is the join
 * point between Data Submissions & Validation and the KPI Explorer — see
 * publishExtractedValues in mocks/handlers/data-submissions.ts, which calls
 * this once per extraction on a publishing decision.
 *
 * Returns false without changing anything if the id does not match a
 * catalogue row, so a bad extraction never partially applies.
 */
export function publishKpiValue(
  extraction: KpiExtraction,
  submissionId: string,
  resultingStatus: 'confirmed' | 'provisional',
): boolean {
  const row = CATALOGUE.find((entry) => entry.id === extraction.kpiId)
  if (!row) return false

  const publishedAt = new Date().toISOString()
  row.lastUpdated = publishedAt
  row.validationStatus = resultingStatus

  const profile = PROFILES[extraction.kpiId]
  if (!profile) return true // Catalogue updated; no bespoke profile to extend.

  profile.current = extraction.value
  profile.currentLabel = `${extraction.value}${profile.unit === '%' ? '%' : ` ${profile.unit}`}`
  profile.reportingPeriod = extraction.reportingPeriod
  profile.validationStatus = resultingStatus
  profile.confidence = resultingStatus === 'confirmed' ? 'confirmed' : 'requires-validation'
  profile.validationDecision = `Published from submission ${submissionId} on ${publishedAt.slice(0, 10)}.`
  profile.provenance = { ...profile.provenance, lastUpdated: publishedAt }
  profile.history = [
    ...profile.history,
    {
      id: `${extraction.kpiId}-submission-${submissionId}`,
      period: extraction.reportingPeriod,
      value: extraction.value,
      validationStatus: resultingStatus,
      submissionId,
      editable: false,
    },
  ]

  return true
}

/**
 * Updates a KPI's definition metadata in place — the admin-editable half of
 * a profile (methodology, baseline, target, source), never `current`/
 * `history`, which only change through publishKpiValue above. Mutates both
 * the bespoke PROFILES entry (if one exists) and the CATALOGUE row's
 * overlapping `name`/`baseline`/`target` fields, so a KPI without a bespoke
 * profile (served via fallbackProfile, which derives from CATALOGUE) still
 * reflects the edit. Returns the resulting profile, or null if the id
 * doesn't exist.
 */
export function updateKpiMetadata(
  id: string,
  patch: {
    pillar: PillarId
    definition: string
    formula: string
    unit: string
    aggregation: string
    frequency: string
    disaggregation: string
    limitations: string
    baseline: number | null
    baselineLabel: string
    target: number | null
    targetLabel: string
    targetDate: string | null
    targets?: { period: string; value: number; label: string }[]
    sourceInstitution: string
    sourceDataset: string
    sourceReference: string
  },
): KpiProfile | null {
  const row = CATALOGUE.find((entry) => entry.id === id)
  if (!row) return null

  row.pillar = patch.pillar
  row.sourceInstitution = patch.sourceInstitution
  row.sourceDataset = patch.sourceDataset
  row.unit = patch.unit
  row.frequency = patch.frequency
  row.lastUpdated = new Date().toISOString()

  const profile = PROFILES[id] ?? getKpiProfile(id)
  if (!profile) return null

  Object.assign(profile, patch)
  PROFILES[id] = profile
  return profile
}

/**
 * Directly sets a KPI's current value and appends a history point — an
 * explicit admin override of the usual rule that a value only ever arrives
 * via an approved data submission (see publishKpiValue above). Materialises
 * a bespoke profile into PROFILES on first use if the KPI only ever had a
 * derived fallbackProfile, so the change actually sticks on the next fetch.
 * Returns null if the id doesn't exist.
 */
export function setKpiCurrentValue(
  id: string,
  patch: {
    value: number
    reportingPeriod: string
    resultingStatus: 'confirmed' | 'provisional'
    note?: string
  },
): KpiProfile | null {
  const row = CATALOGUE.find((entry) => entry.id === id)
  if (!row) return null

  const updatedAt = new Date().toISOString()
  row.lastUpdated = updatedAt
  row.validationStatus = patch.resultingStatus

  const profile = PROFILES[id] ?? getKpiProfile(id)
  if (!profile) return null

  profile.current = patch.value
  // Never stored as free text - always derived from value + unit, matching
  // the real backend's toKpiProfile() exactly (kpi-explorer.mappers.ts).
  profile.currentLabel = `${patch.value}${profile.unit ? ` ${profile.unit}` : ''}`
  profile.reportingPeriod = patch.reportingPeriod
  profile.validationStatus = patch.resultingStatus
  profile.confidence = patch.resultingStatus === 'confirmed' ? 'confirmed' : 'requires-validation'
  profile.validationDecision = patch.note
    ? `Manually set by an administrator: ${patch.note}`
    : 'Manually set by an administrator, outside the data submission workflow.'
  profile.provenance = { ...profile.provenance, lastUpdated: updatedAt }
  profile.history = [
    ...profile.history,
    {
      id: `${id}-override-${Date.now()}`,
      period: patch.reportingPeriod,
      value: patch.value,
      validationStatus: patch.resultingStatus,
      submissionId: null,
      editable: true,
    },
  ]

  PROFILES[id] = profile
  return profile
}

/** Only a point created by setKpiCurrentValue() (editable: true) can be
 * corrected or removed here - mirrors the real backend's
 * findEditableHistoryPoint() guard against touching approved-submission
 * history. Returns null if the KPI or the point itself doesn't exist, or
 * the point isn't editable. */
function findEditableHistoryPoint(id: string, valueId: string) {
  const profile = PROFILES[id] ?? getKpiProfile(id)
  if (!profile) return null
  const point = profile.history.find((entry) => entry.id === valueId)
  if (!point || !point.editable) return null
  return { profile, point }
}

export function editKpiHistoryPoint(
  id: string,
  valueId: string,
  patch: { value: number; reportingPeriod: string; resultingStatus: 'confirmed' | 'provisional'; note?: string },
): KpiProfile | 'not-editable' | null {
  const found = findEditableHistoryPoint(id, valueId)
  if (!found) return profileExistsFor(id) ? 'not-editable' : null
  const { profile, point } = found

  point.period = patch.reportingPeriod
  point.value = patch.value
  point.validationStatus = patch.resultingStatus

  const latest = profile.history.at(-1)
  if (latest === point) {
    profile.current = patch.value
    profile.currentLabel = `${patch.value}${profile.unit ? ` ${profile.unit}` : ''}`
    profile.reportingPeriod = patch.reportingPeriod
    profile.validationStatus = patch.resultingStatus
  }

  PROFILES[id] = profile
  return profile
}

export function deleteKpiHistoryPoint(id: string, valueId: string): KpiProfile | 'not-editable' | null {
  const found = findEditableHistoryPoint(id, valueId)
  if (!found) return profileExistsFor(id) ? 'not-editable' : null
  const { profile } = found

  profile.history = profile.history.filter((entry) => entry.id !== valueId)
  const latest = profile.history.at(-1) ?? null
  profile.current = latest?.value ?? null
  profile.currentLabel = latest ? `${latest.value}${profile.unit ? ` ${profile.unit}` : ''}` : 'No data yet'
  profile.reportingPeriod = latest?.period ?? ''
  profile.validationStatus = latest?.validationStatus ?? 'future'

  PROFILES[id] = profile
  return profile
}

function profileExistsFor(id: string): boolean {
  return Boolean(PROFILES[id] ?? getKpiProfile(id))
}

