/** Builds a plausible profile for any catalogue row lacking a bespoke one. */
function fallbackProfile(row: KpiCatalogueRow): KpiProfile {
  const hasValue = row.validationStatus === 'confirmed' || row.validationStatus === 'public-source'

  return {
    id: row.id,
    name: row.name,
    pillar: row.pillar,
    definition: `Official metadata for ${row.name} is configured in the approved catalogue.`,
    formula: 'As configured in the approved Key Performance Indicator Matrix.',
    unit: row.unit,
    aggregation: 'As configured',
    frequency: row.frequency,
    disaggregation: 'As configured',
    limitations:
      row.validationStatus === 'future'
        ? 'No approved value is currently available for this indicator.'
        : 'See the approved catalogue for configured limitations.',
    baseline: null,
    baselineLabel: 'Not configured',
    current: hasValue ? 0 : null,
    currentLabel: hasValue ? `Awaiting display value (${row.unit})` : 'No current value',
    target: null,
    targetLabel: 'Not configured',
    varianceLabel: 'Not computable without a target',
    direction: 'higher-is-better',
    history: [],
    sourceInstitution: row.sourceInstitution,
    sourceDataset: row.sourceDataset,
    sourceReference: 'As configured',
    reportingPeriod: 'Latest available',
    validationStatus: row.validationStatus,
    validationDecision:
      row.validationStatus === 'requires-validation'
        ? 'Awaiting validation — not to be treated as confirmed.'
        : row.validationStatus === 'future'
          ? 'No value submitted.'
          : 'See submission and validation records.',
    version: 'v1.0',
    confidence: row.validationStatus === 'confirmed' ? 'confirmed' : 'requires-validation',
    provenance: {
      definition: `Catalogue metadata for ${row.name}.`,
      methodology: 'As configured in the approved catalogue.',
      source: `${row.sourceInstitution}.`,
      lastUpdated: row.lastUpdated,
    },
    linkedRecords: [],
  }
}

export function getKpiProfile(id: string): KpiProfile | undefined {
  const bespoke = PROFILES[id]
  if (bespoke) return bespoke

  const row = CATALOGUE.find((entry) => entry.id === id)
  return row ? fallbackProfile(row) : undefined
}

/**
 * Publishes one value extracted from an approved or provisionally-accepted
 * data submission: appends a history point and updates the current value in
 * place, so the KPI Explorer reflects it on the next fetch. This is the join
 * point between Data Submissions & Validation and the KPI Explorer — see
 * publishExtractedValues in mocks/handlers/data-submissions.ts, which calls
 * this once per extraction on a publishing decision.
 *
 * Returns false without changing anything if the id does not match a
 * catalogue row, so a bad extraction never partially applies.
 */
export function publishKpiValue(
  extraction: KpiExtraction,
  submissionId: string,
  resultingStatus: 'confirmed' | 'provisional',
): boolean {
  const row = CATALOGUE.find((entry) => entry.id === extraction.kpiId)
  if (!row) return false

  const publishedAt = new Date().toISOString()
  row.lastUpdated = publishedAt
  row.validationStatus = resultingStatus

  const profile = PROFILES[extraction.kpiId]
  if (!profile) return true // Catalogue updated; no bespoke profile to extend.

  profile.current = extraction.value
  profile.currentLabel = `${extraction.value}${profile.unit === '%' ? '%' : ` ${profile.unit}`}`
  profile.reportingPeriod = extraction.reportingPeriod
  profile.validationStatus = resultingStatus
  profile.confidence = resultingStatus === 'confirmed' ? 'confirmed' : 'requires-validation'
  profile.validationDecision = `Published from submission ${submissionId} on ${publishedAt.slice(0, 10)}.`
  profile.provenance = { ...profile.provenance, lastUpdated: publishedAt }
  profile.history = [
    ...profile.history,
    {
      period: extraction.reportingPeriod,
      value: extraction.value,
      validationStatus: resultingStatus,
      submissionId,
    },
  ]

  return true
}

