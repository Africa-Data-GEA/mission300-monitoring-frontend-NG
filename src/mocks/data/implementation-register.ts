/** Derives the four headline cards from the register so they never drift. */
function buildOverview(): ImplementationRegisterOverview {
  const priorityMilestones = MILESTONES.filter((m) => m.priority === 'priority')
  const dueMilestones = priorityMilestones.filter(
    (m) => new Date(m.expectedDate) <= new Date('2025-10-14T00:00:00Z'),
  )
  const completedOnTime = dueMilestones.filter(
    (m) => m.status === 'completed' && m.actualDate && m.actualDate <= m.expectedDate,
  )
  const delayedMilestones = dueMilestones.filter((m) => m.status === 'delayed' || m.status === 'at-risk')
  const blockedMilestones = dueMilestones.filter((m) => m.status === 'blocked')

  const allRecords = [
    ...PROGRAMMES.map((r) => ({ status: r.status })),
    ...PROJECTS.map((r) => ({ status: r.status })),
    ...MILESTONES.map((r) => ({ status: r.status })),
    ...ACTIONS.map((r) => ({ status: r.status })),
  ]
  const delayedOrBlocked = allRecords.filter(
    (r) => r.status === 'delayed' || r.status === 'blocked',
  )

  const missingEvidence = [
    ...PROJECTS.filter((r) => r.status !== 'completed' && !r.evidenceUrl),
    ...MILESTONES.filter((r) => r.status !== 'completed' && !r.evidenceUrl),
    ...ACTIONS.filter((r) => r.status !== 'completed' && !r.evidenceUrl),
  ]

  return {
    lastUpdated: '2025-10-14T09:12:00Z',
    headlineCards: {
      summary: {
        title: 'Active programmes and projects',
        icon: 'milestones',
        activeProgrammes: PROGRAMMES.filter((p) => p.status !== 'completed').length,
        activeProjects: PROJECTS.filter((p) => p.status !== 'completed').length,
        newThisCycle: 2,
        closedThisCycle: 1,
        trend: { change: 2, label: '+2 vs Q2 2025', direction: 'higher-is-better' },
        provenance: {
          definition: 'Approved active programmes and projects in the register.',
          methodology: 'Count unique active programme records and unique active project records separately.',
          source: 'Implementation Register and institutional project registers.',
          lastUpdated: '2025-10-14T09:12:00Z',
        },
      },
      milestoneOnTime: {
        title: 'Priority milestones delivered on time',
        icon: 'milestones',
        percentOnTime:
          dueMilestones.length === 0
            ? 0
            : Math.round((completedOnTime.length / dueMilestones.length) * 100),
        dueCount: dueMilestones.length,
        completedCount: completedOnTime.length,
        delayedCount: delayedMilestones.length,
        blockedCount: blockedMilestones.length,
        targetLabel: '100% of due priority milestones delivered on time',
        trend: { change: -8, label: '-8pp vs Q2 2025', direction: 'higher-is-better' },
        provenance: {
          definition: 'Priority milestones completed by their due dates.',
          methodology:
            'On-time completed priority milestones divided by priority milestones due by the selected date, multiplied by 100.',
          source: 'Compact Progress Report and Implementation Register.',
          lastUpdated: '2025-10-14T09:12:00Z',
        },
      },
      delayedOrBlocked: {
        title: 'Delayed or blocked records',
        icon: 'escalations',
        count: delayedOrBlocked.length,
        targetLabel: 'Zero delayed or blocked priority records',
        supportingLabel: `affects ${new Set(PROGRAMMES.filter((p) => p.status === 'delayed' || p.status === 'blocked').map((p) => p.pillar)).size} pillars`,
        trend: { change: 1, label: '+1 vs Q2 2025', direction: 'lower-is-better' },
        provenance: {
          definition: 'Approved priority records currently delayed or blocked.',
          methodology: 'Count unique register records with current status Delayed or Blocked.',
          source: 'Implementation Register.',
          lastUpdated: '2025-10-14T09:12:00Z',
        },
      },
      evidenceOverdue: {
        title: 'Records requiring evidence or update',
        icon: 'generic',
        count: missingEvidence.length,
        targetLabel: 'Zero overdue priority records without current evidence or update',
        supportingLabel: 'median 26 days since last update',
        trend: { change: -1, label: '-1 vs Q2 2025', direction: 'lower-is-better' },
        provenance: {
          definition: 'Priority records missing required evidence or a current update.',
          methodology: 'Count records whose evidence field is missing or whose required update date has passed.',
          source: 'Implementation Register and evidence log.',
          lastUpdated: '2025-10-14T09:12:00Z',
        },
      },
    },
    programmes: { items: PROGRAMMES, page: 1, pageSize: 10, total: PROGRAMMES.length },
    projects: { items: PROJECTS, page: 1, pageSize: 10, total: PROJECTS.length },
    milestones: { items: MILESTONES, page: 1, pageSize: 10, total: MILESTONES.length },
    actions: { items: ACTIONS, page: 1, pageSize: 10, total: ACTIONS.length },
  }
}

