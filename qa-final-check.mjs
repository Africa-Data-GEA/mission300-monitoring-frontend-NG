import { chromium } from 'playwright'
const BASE='http://localhost:5179'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport:{width:1500,height:1100} })
const errs=[], bad=[]
page.on('console', m=>{ if(m.type()==='error') errs.push(m.text()) })
page.on('pageerror', e=>errs.push('PAGEERROR: '+e.message))
page.on('response', r=>{ if(r.status()>=400 && r.url().includes('3001')) bad.push(r.status()+' '+r.url()) })
await page.goto(`${BASE}/account/login`,{waitUntil:'networkidle'})
await page.locator('input[type="email"]').first().fill('admin@m300.local')
await page.locator('button[type="submit"]').first().click()
await page.waitForURL('**/account/password')
await page.locator('input[name="password"]').first().fill('ChangeMe123!')
await page.locator('button[type="submit"]').first().click()
await page.waitForURL('**/dashboard',{timeout:20000})
await page.waitForTimeout(9000)
const eo = await page.locator('body').innerText()
console.log('EXEC ATC&C:', (eo.match(/ATC&C Loss Rate[\s\S]{0,60}?([\d.]+%)/)||[])[1])
await page.goto(`${BASE}/programs`,{waitUntil:'networkidle'}); await page.waitForTimeout(7000)
await page.screenshot({path:'qa-screenshots/final-programs.png',fullPage:true})
const pg = await page.locator('body').innerText()
console.log('programs page has NISO:', /NISO/i.test(pg))
console.log('programs page shows "Not set":', /Not set/.test(pg))
await page.goto(`${BASE}/state-disco`,{waitUntil:'networkidle'}); await page.waitForTimeout(8000)
const sd = await page.locator('body').innerText()
console.log('STATE&DISCO ATC&C:', (sd.match(/Aggregate Technical[\s\S]{0,80}?([\d.]+%)/)||[])[1])
console.log('console errors:', errs.length?errs.slice(0,3):'none')
console.log('bad responses:', bad.length?bad.slice(0,3):'none')
await browser.close()
