import { chromium } from 'playwright'
const BASE = 'http://localhost:5179'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1600, height: 1200 } })
await page.goto(`${BASE}/account/login`, { waitUntil: 'networkidle' })
await page.locator('input[type="email"]').first().fill('admin@m300.local')
await page.locator('button[type="submit"]').first().click()
await page.waitForURL('**/account/password')
await page.locator('input[name="password"]').first().fill('ChangeMe123!')
await page.locator('button[type="submit"]').first().click()
await page.waitForURL('**/dashboard', { timeout: 20000 })
await page.waitForTimeout(8000)
const sec = page.locator('text=National performance and target progress').locator('..').locator('..')
await sec.screenshot({ path: 'qa-screenshots/final-progress-tab.png' })
const tab = page.getByRole('tab', { name: /trend/i }).first()
if (await tab.count()) { await tab.click(); await page.waitForTimeout(3500) }
await sec.screenshot({ path: 'qa-screenshots/final-trend-tab.png' })
const t = await page.locator('body').innerText()
console.log('pp/unit trend labels visible:', [...new Set(t.match(/[+-]?[\d.]+\s?(pp|MW|%)\s+vs\s+[A-Z0-9 ]{2,9}/g) || [])].slice(0,8))
console.log('unrounded floats:', [...new Set(t.match(/\d+\.\d{5,}/g) || [])].length)
console.log('raw period codes:', [...new Set(t.match(/\bq[1-4]-\d{4}\b/g) || [])].length)
await browser.close()
